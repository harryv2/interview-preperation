package main

type Facts map[string]any

func (f Facts) Number(key string) (float64, bool) {
	return toFloat(f[key])
}

func toFloat(v any) (float64, bool) {
	switch n := v.(type) {
	case int:
		return float64(n), true
	case int64:
		return float64(n), true
	case float32:
		return float64(n), true
	case float64:
		return n, true
	default:
		return 0, false
	}
}
